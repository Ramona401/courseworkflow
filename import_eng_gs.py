def build_kp_index(code, depth, kp, b, e, s, h, dm, cc_dot):
    """拼装 kp_index 行, 与人工核对版完全一致(符号段 SJ|SG|GR|DP, 语义段 K B E S H DM CC)"""
    return (f"KP {code} | SJ:E|SG:5|GR:0|DP:{depth} "
            f"[K]{kp} [B]{b} [E]{e} [S]{s} [H]{h} [DM]{dm} [CC]{cc_dot}")

def assemble():
    """组装44条完整记录, 同时做内存校验"""
    records = []
    seen_codes = set()
    errors = []
    for r in ROWS:
        (code, seg, domain, kp, creq, areq, skill, hint, depth, cc_cn, dm, cc_dot) = r
        # 校验1: kp_code 唯一
        if code in seen_codes:
            errors.append(f"重复kp_code: {code}")
        seen_codes.add(code)
        # 校验2: depth 1-3
        if depth not in (1,2,3):
            errors.append(f"{code} depth非法: {depth}")
        # 校验3: seg 合法
        if seg not in SEG_CN:
            errors.append(f"{code} seg非法: {seg}")
        # 校验4: 三要素非空
        if not kp or not creq or not areq:
            errors.append(f"{code} K/B/E有空")
        kp_index = build_kp_index(code, depth, kp, creq, areq, skill, hint, dm, cc_dot)
        # 校验5: kp_index 非空且含KP开头
        if not kp_index.startswith("KP "):
            errors.append(f"{code} kp_index格式错")
        source_ref = f"{SRC_PREFIX}·{SEG_CN[seg]}·{domain}"
        # 校验6: 字段长度(防超表约束 kp_code<=40, kp_name<=300, source_ref<=300, core_competency<=200)
        if len(code) > 40: errors.append(f"{code} kp_code超40")
        if len(kp) > 300: errors.append(f"{code} kp_name超300")
        if len(source_ref) > 300: errors.append(f"{code} source_ref超300")
        if len(cc_cn) > 200: errors.append(f"{code} core_competency超200")
        records.append({
            "subject": SUBJECT, "stage": STAGE, "grade_num": GRADE_NUM,
            "domain": domain, "theme": THEME, "kp_code": code, "kp_name": kp,
            "content_requirement": creq, "academic_requirement": areq,
            "teaching_hint": hint, "depth_level": depth,
            "core_competency": cc_cn, "kp_index": kp_index,
            "idx_depth_level": IDX_DEPTH, "source_ref": source_ref,
            "confidence": CONFIDENCE, "sort_order": SORT_ORDER,
            "status": STATUS, "extra": EXTRA, "batch_tag": BATCH_TAG,
        })
    return records, errors

def main():
    dry = "--dry-run" in sys.argv
    records, errors = assemble()
    print(f"=== 组装记录数: {len(records)} (应为44) ===")
    print(f"=== 段码分布: GS1={sum(1 for r in records if '-GS1-' in r['kp_code'])} "
          f"GS2={sum(1 for r in records if '-GS2-' in r['kp_code'])} "
          f"GS3={sum(1 for r in records if '-GS3-' in r['kp_code'])} ===")
    if errors:
        print("=== 校验错误(终止): ===")
        for e in errors:
            print("  !", e)
        sys.exit(1)
    print("=== 内存校验全部通过(唯一性/depth/seg/三要素/格式/长度) ===")

    if dry:
        print("=== [DRY-RUN] 不连库。抽样打印前2条与后1条 kp_index: ===")
        for r in [records[0], records[1], records[-1]]:
            print("  " + r["kp_index"])
        print("=== [DRY-RUN] source_ref 抽样: ===")
        for r in [records[0], records[6], records[-1]]:
            print(f"  {r['kp_code']} -> {r['source_ref']}")
        print("=== [DRY-RUN] 结束, 未写入任何数据 ===")
        return

    # ===== 真正入库(仅非 dry-run) =====
    import psycopg2
    from psycopg2.extras import execute_values
    # 从环境变量或 .env 读取连接
    dsn = dict(
        host=os.environ.get("DB_HOST","127.0.0.1"),
        port=os.environ.get("DB_PORT","5432"),
        dbname=os.environ.get("DB_NAME","tedna"),
        user=os.environ.get("DB_USER","tedna_user"),
        password=os.environ.get("DB_PASSWORD",""),
    )
    cols = ["subject","stage","grade_num","domain","theme","kp_code","kp_name",
            "content_requirement","academic_requirement","teaching_hint","depth_level",
            "core_competency","kp_index","idx_depth_level","source_ref","confidence",
            "sort_order","status","extra","batch_tag"]
    values = [[r[c] for c in cols] for r in records]
    sql = f"""
    INSERT INTO curriculum_standards ({",".join(cols)})
    VALUES %s
    ON CONFLICT (kp_code) DO UPDATE SET
      subject=EXCLUDED.subject, stage=EXCLUDED.stage, grade_num=EXCLUDED.grade_num,
      domain=EXCLUDED.domain, theme=EXCLUDED.theme, kp_name=EXCLUDED.kp_name,
      content_requirement=EXCLUDED.content_requirement,
      academic_requirement=EXCLUDED.academic_requirement,
      teaching_hint=EXCLUDED.teaching_hint, depth_level=EXCLUDED.depth_level,
      core_competency=EXCLUDED.core_competency, kp_index=EXCLUDED.kp_index,
      idx_depth_level=EXCLUDED.idx_depth_level, source_ref=EXCLUDED.source_ref,
      confidence=EXCLUDED.confidence, sort_order=EXCLUDED.sort_order,
      status=EXCLUDED.status, extra=EXCLUDED.extra, batch_tag=EXCLUDED.batch_tag,
      updated_at=now()
    """
    conn = psycopg2.connect(**dsn)
    try:
        with conn:
            with conn.cursor() as cur:
                execute_values(cur, sql, values, template="(" + ",".join(["%s"]*len(cols)) + ")")
                print(f"=== 已提交 upsert {len(values)} 条 ===")
        print("=== 事务成功提交 ===")
    except Exception as ex:
        conn.rollback()
        print("=== 入库失败,已回滚:", ex)
        sys.exit(1)
    finally:
        conn.close()

if __name__ == "__main__":
    main()
